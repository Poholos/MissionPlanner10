#!/usr/bin/env bash
set -euo pipefail

readonly expected_source_commit="8ed19081c972a80a8b6996ed817581bc59cbcb4b"
readonly native_baseline_commit="67a3c4f22bd1b38ac499f9756902e04fa4ed8444"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo_root="$(cd "$script_dir/../.." && pwd -P)"
source_port="${1:-$repo_root/../MissionPlanner-Avalonia}"
source_manifest="$repo_root/Porting/PORT_SOURCE_IMPORT.tsv"

actual_source_commit="$(git -C "$source_port" rev-parse HEAD)"
if [[ "$actual_source_commit" != "$expected_source_commit" ]]; then
  echo "Expected port source $expected_source_commit, found $actual_source_commit" >&2
  exit 1
fi
if ! git -C "$source_port" diff --quiet || ! git -C "$source_port" diff --cached --quiet; then
  echo "The port source worktree is dirty; refuse an ambiguous import." >&2
  exit 1
fi
if [[ "$(git -C "$repo_root" rev-parse --abbrev-ref HEAD)" != "port/avalonia-in-place" ]]; then
  echo "Run the import only on port/avalonia-in-place." >&2
  exit 1
fi
if [[ ! -f "$source_manifest" ]]; then
  echo "Missing source manifest: $source_manifest" >&2
  exit 1
fi

temporary_dir="$(mktemp -d)"
trap 'rm -rf -- "$temporary_dir"' EXIT
import_record="$temporary_dir/IMPORTED_APPLICATION.tsv"
compile_items="$temporary_dir/ImportedApplicationItems.props"
printf 'source_path\tnative_path\tsource_blob\tnamespace_migration\n' > "$import_record"

baseline_program_blob="$(git -C "$repo_root" rev-parse "$native_baseline_commit:Program.cs")"
imported=0
skipped=0

while IFS=$'\t' read -r source_path target_path action notes; do
  [[ "$source_path" == "source_path" ]] && continue
  [[ "$source_path" == src/MissionPlannerAvalonia/* ]] || continue
  [[ "$source_path" != src/MissionPlannerAvalonia/MissionPlannerAvalonia.csproj ]] || continue
  if [[ "$action" != "import" && "$action" != "replace" ]]; then
    continue
  fi
  if [[ -z "$target_path" || "$target_path" == /* || "$target_path" == *".."* ]]; then
    echo "Unsafe target mapping for $source_path: $target_path" >&2
    exit 1
  fi

  source_blob="$(git -C "$source_port" rev-parse "$expected_source_commit:$source_path")"
  original="$temporary_dir/original"
  candidate="$temporary_dir/candidate"
  git -C "$source_port" show "$expected_source_commit:$source_path" > "$original"

  namespace_migration="none"
  case "$source_path" in
    *.cs|*.axaml|*.manifest)
      sed 's/MissionPlannerAvalonia/MissionPlanner/g' "$original" > "$candidate"
      namespace_migration="MissionPlannerAvalonia->MissionPlanner"
      ;;
    *)
      cp "$original" "$candidate"
      ;;
  esac

  destination="$repo_root/$target_path"
  if [[ -e "$destination" ]]; then
    if cmp -s "$candidate" "$destination"; then
      skipped=$((skipped + 1))
    elif [[ "$target_path" == "Program.cs"
        && "$(git -C "$repo_root" hash-object Program.cs)" == "$baseline_program_blob" ]]; then
      install -D -m 0644 "$candidate" "$destination"
      imported=$((imported + 1))
    else
      echo "Refusing to overwrite an unexpected target: $target_path" >&2
      exit 1
    fi
  else
    install -D -m 0644 "$candidate" "$destination"
    imported=$((imported + 1))
  fi

  printf '%s\t%s\t%s\t%s\n' \
    "$source_path" "$target_path" "$source_blob" "$namespace_migration" >> "$import_record"
done < "$source_manifest"

{
  printf '<Project>\n'
  printf '  <!-- Generated by build/porting/import-application.sh from the pinned source manifest. -->\n'
  printf '  <ItemGroup>\n'
  while IFS=$'\t' read -r source_path target_path source_blob namespace_migration; do
    [[ "$source_path" == "source_path" ]] && continue
    case "$target_path" in
      *.cs)
        printf '    <Compile Include="$(MSBuildThisFileDirectory)../%s" />\n' "$target_path"
        ;;
    esac
  done < "$import_record"
  printf '  </ItemGroup>\n'
  printf '</Project>\n'
} > "$compile_items"

mv "$import_record" "$repo_root/Porting/IMPORTED_APPLICATION.tsv"
mv "$compile_items" "$repo_root/Porting/ImportedApplicationItems.props"
echo "Imported $imported application files; $skipped already matched."
